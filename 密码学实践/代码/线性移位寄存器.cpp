#include <bits/stdc++.h>
using namespace std;

int main() {
    // 定义第一个线性反馈移位寄存器的状态数组（初始值：001）
    int b[3] = {0, 0, 1};
    
    // 输出第一个LFSR的20位序列
    cout << "第一个线性反馈移位寄存器输出为：" << endl;
    for (int i = 0; i < 20; i++) {
        cout << b[0] << ' ';  // 输出当前最低位（最右边的位）
        
        // 移位操作：将寄存器向右移动一位（高位丢失，低位补0）
        b[0] = b[1];  // 原次低位变为新最低位
        b[1] = b[2];  // 原最高位变为新次低位
        
        // 反馈函数：新最高位由原次低位和原最低位异或生成（反馈多项式 x^3 + x^2 + 1）
        b[2] = (b[0] + b[1]) % 2;  
    }
    cout << endl;
    
    // 重置寄存器状态为初始值（001）
    b[0] = 0; b[1] = 0; b[2] = 1;
    
    // 输出第二个LFSR的20位序列（与第一个的区别在于反馈逻辑）
    cout << "第二个线性反馈移位寄存器输出为：" << endl;
    for (int i = 0; i < 20; i++) {
        cout << b[0] << ' ';  // 输出当前最低位
        
        // 保存当前最低位用于反馈计算（临时变量a）
        int a = b[0];
        
        // 移位操作（同第一个LFSR）
        b[0] = b[1];
        b[1] = b[2];
        
        // 反馈函数：新最高位由原最低位和原次低位异或生成（反馈多项式 x^3 + x + 1）
        b[2] = (a + b[1]) % 2;  
    }
    return 0;
}
